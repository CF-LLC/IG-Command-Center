import type { DB } from "./types";

function daysAgo(n: number) {
  const d = new Date();
  d.setDate(d.getDate() - n);
  return d.toISOString();
}

function daysFromNow(n: number) {
  const d = new Date();
  d.setDate(d.getDate() + n);
  return d.toISOString();
}

function series(baseFollowers: number): DB["analytics"][string] {
  return Array.from({ length: 30 }, (_, i) => {
    const day = 29 - i;
    return {
      date: daysAgo(day).slice(0, 10),
      followers: Math.round(baseFollowers - day * 12 + Math.sin(i) * 40),
      reach: Math.round(1800 + Math.sin(i / 2) * 600 + i * 20),
      engagement: Number((3.1 + Math.sin(i / 3) * 0.8).toFixed(2)),
      impressions: Math.round(4200 + Math.cos(i / 2) * 900 + i * 35),
    };
  });
}

